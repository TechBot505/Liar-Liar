import type { NextConfig } from "next";

/**
 * Security headers are intentionally conservative. We do NOT set a
 * Content-Security-Policy here: a strict CSP would break the PartySocket
 * WebSocket connection and Clerk's scripts/frames. Add one later only after
 * enumerating PartyKit + Clerk origins.
 */
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "X-Frame-Options", value: "DENY" },
  // Minimal Permissions-Policy: deny sensitive features we do not use.
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), browsing-topics=()" },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [
      { source: "/:path*", headers: securityHeaders },
      {
        // The service worker must not be cached and needs a broad scope.
        source: "/sw.js",
        headers: [
          { key: "Cache-Control", value: "no-cache, no-store, must-revalidate" },
          { key: "Service-Worker-Allowed", value: "/" },
        ],
      },
    ];
  },
};

export default nextConfig;
